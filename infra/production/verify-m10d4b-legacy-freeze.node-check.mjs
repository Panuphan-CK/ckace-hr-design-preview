import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { verifyM10D4B, verifyM10D4BFiles } from "./verify-m10d4b-legacy-freeze.mjs";
const here = path.dirname(fileURLToPath(import.meta.url));
const originals = () => ["m10d4b-legacy-freeze-preparation.json", "m10d4-preexecution-readiness.json"].map(f => JSON.parse(readFileSync(path.join(here,f),"utf8")));
test("blocked preparation evidence is internally consistent",()=>assert.equal(verifyM10D4BFiles().pathCount,15));
test("cannot claim source implementation while mutation lock persists",()=>{const [a,b]=originals();a.gates.sourceEdits="PASS";assert.throws(()=>verifyM10D4B(a,b));});
test("cannot claim production authorization",()=>{const [a,b]=originals();a.gates.productionExecutionApproval="GRANTED";assert.throws(()=>verifyM10D4B(a,b));});
test("cannot ignore automated entitlement writes",()=>{const [a,b]=originals();a.sourceInventory.paths=a.sourceInventory.paths.filter(x=>x.id!=="onboarding-default-policy");assert.throws(()=>verifyM10D4B(a,b));});
test("cannot pretend a valid freeze test passed",()=>{const [a,b]=originals();a.gates.isolatedGASBehaviorTests="PASS";assert.throws(()=>verifyM10D4B(a,b));});
test("cannot report nonlegacy authority",()=>{const [a,b]=originals();a.gates.cutoverAuthority="NEW";assert.throws(()=>verifyM10D4B(a,b));});
